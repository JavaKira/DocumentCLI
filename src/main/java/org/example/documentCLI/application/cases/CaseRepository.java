package org.example.documentCLI.application.cases;

import org.example.documentCLI.domain.Case;

import java.util.List;
import java.util.Optional;

/**
 * Репозиторий дел: абстракция над хранилищем.
 *
 * <p>Отвечает за персистентность записей {@link Case}. Реализации могут
 * работать с файловой системой, БД или in-memory структурами.</p>
 *
 * <p>Методы репозитория не выполняют бизнес-валидацию (например, не проверяют
 * уникальность {@code regNumber} или корректность {@code fundId}) — это
 * ответственность сервисного слоя. Репозиторий лишь сохраняет и извлекает
 * данные в том виде, в котором они были переданы.</p>
 *
 * @author Javakira
 * @since 1.0
 */
public interface CaseRepository {

    /**
     * Возвращает все дела из хранилища.
     *
     * @return неизменяемый список дел; пустой список, если дел нет
     */
    List<Case> all();

    /**
     * Находит дело по идентификатору.
     *
     * @param id идентификатор дела (например, {@code 0001-2026}, {@code ВУ}, {@code ПСИ-1})
     * @return найденное дело
     * @throws IllegalArgumentException если дело с таким id не найдено
     */
    Case byId(String id);

    /**
     * Проверяет существование дела.
     *
     * @param id идентификатор дела
     * @return {@code true}, если дело есть в хранилище
     */
    boolean exists(String id);

    /**
     * Сохраняет дело (создание или обновление).
     *
     * <p>Контракт — upsert. Возвращается актуальная версия дела
     * после сохранения.</p>
     *
     * @param c дело для сохранения
     * @return сохранённое дело
     */
    Case update(Case c);

    /**
     * Удаляет дело по идентификатору.
     *
     * <p>Операция идемпотентна: если дела нет — завершается без ошибки.</p>
     *
     * @param id идентификатор дела
     */
    void delete(String id);
}