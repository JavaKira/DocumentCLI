package org.example.documentCLI.application.fund;

import org.example.documentCLI.domain.Fund;

import java.util.List;

/**
 * Репозиторий фондов: абстракция над хранилищем.
 *
 * <p>Отвечает за персистентность записей {@link Fund}. Реализации могут
 * работать с файловой системой, БД или in-memory структурами.</p>
 *
 * <p>Методы репозитория не выполняют бизнес-валидацию (например, не проверяют
 * уникальность названия фонда) — это ответственность сервисного слоя.
 * Репозиторий лишь сохраняет и извлекает данные в том виде, в котором они
 * были переданы.</p>
 *
 * @author Javakira
 * @since 1.0
 */
public interface FundRepository {

    /**
     * Возвращает все фонды из хранилища.
     *
     * @return неизменяемый список фондов; пустой список, если фондов нет
     */
    List<Fund> all();

    /**
     * Находит фонд по идентификатору.
     *
     * @param id идентификатор фонда
     * @return найденный фонд
     * @throws IllegalArgumentException если фонд с таким id не найден
     */
    Fund byId(Integer id);

    /**
     * Проверяет существование фонда.
     *
     * @param id идентификатор фонда
     * @return {@code true}, если фонд есть в хранилище
     */
    boolean exists(Integer id);

    /**
     * Сохраняет фонд (создание или обновление).
     *
     * <p>Контракт — upsert. Возвращается актуальная версия фонда
     * после сохранения.</p>
     *
     * @param fund фонд для сохранения
     * @return сохранённый фонд
     */
    Fund update(Fund fund);

    /**
     * Удаляет фонд по идентификатору.
     *
     * <p>Операция идемпотентна: если фонда нет — завершается без ошибки.</p>
     *
     * @param id идентификатор фонда
     */
    void delete(Integer id);
}